export function findSyntheticSpec(id: string): SyntheticSpec | undefined {
  return SYNTHETIC_DOCUMENTS.find(spec => spec.id === id);
}

/** Build the demo PDF + canned OCR for a synthetic document, as of `now`. */
export function buildSyntheticDocument(
  id: string,
  now = new Date(),
): SyntheticBuiltDocument | undefined {
  const spec = findSyntheticSpec(id);
  if (!spec) return undefined;
  return {
    id: spec.id,
    filename: spec.filename,
    mimeType: "application/pdf",
    pdfBytes: makeSimplePdf(spec.buildLines(now)),
    ocrPages: spec.buildOcrPages(now),
  };
}
