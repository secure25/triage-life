import type { OcrPage } from "../../drizzle/schema";

/**
 * Synthetic demo documents (spec §10).
 *
 * Each demo document is a real (minimal) PDF whose visible text includes a
 * marker line `TRIAGE-SYNTHETIC:<id>`. The demo OCR provider recognizes that
 * marker and returns realistic OCR text; the deterministic extractor then
 * parses that text like it would any other document. Dates are generated
 * relative to "now" so the demo never goes stale.
 *
 * Demo documents can never contact a real third party: every address uses
 * the reserved `.example` TLD.
 */

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function addDays(base: Date, days: number): Date {
  return new Date(base.getTime() + days * 24 * 60 * 60 * 1000);
}

function formatDate(date: Date): string {
  return `${MONTHS[date.getMonth()]} ${date.getDate()}, ${date.getFullYear()}`;
}

// ---------------------------------------------------------------------------
// Minimal PDF writer (uncompressed, single font, Helvetica). Enough to
// produce a valid, openable PDF containing the document text.
// ---------------------------------------------------------------------------

function escapePdfText(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

export function makeSimplePdf(lines: string[]): Buffer {
  const contentLines = lines
    .map((line, index) => {
      const escaped = escapePdfText(line);
      return index === 0
        ? `(${escaped}) Tj`
        : `(${escaped}) Tj T*`;
    })
    .join("\n");

  const content = `BT\n/F1 11 Tf\n50 742 Td\n16 TL\n${contentLines}\nET`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R " +
      "/Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(content, "latin1")} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(pdf, "latin1"));
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = Buffer.byteLength(pdf, "latin1");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${offset.toString().padStart(10, "0")} 00000 n \n`;
  }
  pdf +=
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n` +
    `startxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, "latin1");
}

